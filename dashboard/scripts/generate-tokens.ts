// Regenerates src/app/m3-tokens.css (the default dynamic-color scheme) from the seed.
//   npm run tokens
import { writeFileSync } from "node:fs";
import { DEFAULT_SEED, schemeCss } from "../src/lib/m3-theme.ts";

const header = `/* Generated by scripts/generate-tokens.ts from seed ${DEFAULT_SEED}. Do not edit by hand. */\n\n`;
writeFileSync(new URL("../src/app/m3-tokens.css", import.meta.url), header + schemeCss(DEFAULT_SEED) + "\n");
console.log("wrote src/app/m3-tokens.css");
